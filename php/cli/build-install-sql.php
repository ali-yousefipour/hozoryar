<?php
declare(strict_types=1);
if(PHP_SAPI!=='cli'){http_response_code(403);exit;}
$directory=dirname(__DIR__).'/db';
$files=glob($directory.'/[0-9][0-9][0-9]_*.sql');sort($files);
if(!$files)throw new RuntimeException('No numbered migrations found');
$sql="-- Hozoryar: fresh installation only. Select a NEW EMPTY database in phpMyAdmin.\n"
    ."-- Generated by php php/cli/build-install-sql.php; no users, passwords or live data included.\n"
    ."-- Do not import this file together with the numbered migrations.\n"
    ."SET NAMES utf8mb4;\nSET SESSION time_zone = '+03:30';\n\n"
    ."CREATE TABLE schema_migrations (\n"
    ." name VARCHAR(120) PRIMARY KEY, checksum CHAR(64) NOT NULL,\n"
    ." status VARCHAR(16) NOT NULL, applied_at DATETIME NULL\n"
    .") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n";
foreach($files as $file){
    $name=basename($file);
    $source=str_replace(["\r\n","\r"],"\n",file_get_contents($file));
    $hash=hash('sha256',$source);
    $sql.="\n-- BEGIN $name\nINSERT INTO schema_migrations(name,checksum,status) VALUES('$name','$hash','started');\n";
    // A fresh-install bundle must stop on existing tables instead of merging schemas.
    $sql.=preg_replace('/CREATE TABLE IF NOT EXISTS /i','CREATE TABLE ',$source);
    $sql.="\nUPDATE schema_migrations SET status='applied',applied_at=UTC_TIMESTAMP() WHERE name='$name';\n-- END $name\n";
}
$output=$directory.'/migrations/hozoryar-install.sql';
if(in_array('--check',$argv,true)){
    if(!is_file($output)||str_replace("\r\n","\n",file_get_contents($output))!==$sql){
        fwrite(STDERR,"Fresh-install SQL is missing or stale. Run php php/cli/build-install-sql.php.\n");exit(1);
    }
    echo "Fresh-install SQL matches all numbered migrations.\n";exit;
}
if(!is_dir(dirname($output)))mkdir(dirname($output),0755,true);
file_put_contents($output,$sql);
echo "Generated $output (".count($files)." migrations).\n";
